def _tree(client: TestClient, part_id: str, owner: str = OWNER) -> dict[str, Any]:
    response = client.get(f"/api/v1/parts/{part_id}/features", headers=_headers(owner))
    assert response.status_code == 200, response.text
    body: dict[str, Any] = response.json()
    return body


def _sketch_and_extrude(client: TestClient, part_id: str) -> tuple[str, str]:
    """§6 worked example: Sketch1 at 0, Extrude1 at 1. Returns their ids."""
    sketch = _create_feature(client, part_id, "Sketch1", _sketch_envelope(), 0)
    sketch_id: str = sketch["feature"]["id"]
    extrude = _create_feature(
        client, part_id, "Extrude1", _extrude_envelope(sketch_id), 1
    )
    extrude_id: str = extrude["feature"]["id"]
    return sketch_id, extrude_id


def direct_engine(url: str) -> AsyncEngine:
    """A direct-inspection engine with SQLite FK enforcement matching the app."""
    engine = create_async_engine(async_dsn(url))
    enable_sqlite_foreign_keys(engine)
    return engine


async def _fetch_all(url: str, statement: sa.Select[Any]) -> list[sa.Row[Any]]:
    engine = direct_engine(url)
    try:
        async with engine.connect() as connection:
            return list((await connection.execute(statement)).all())
    finally:
        await engine.dispose()


# --- §6 worked example round-trip -------------------------------------------------


def test_worked_example_rows_round_trip(client: TestClient, any_db_url: str) -> None:
    part_id = _create_part(client)
    sketch_id, extrude_id = _sketch_and_extrude(client, part_id)

    tree = _tree(client, part_id)
    assert tree["part_id"] == part_id
    assert tree["tree_version"] == 2  # two mutations
    assert tree["rollback_feature_id"] is None

    sketch, extrude = tree["features"]
    # Row 1 — the sketch, §6 verbatim.
    assert (sketch["order_index"], sketch["name"]) == (0, "Sketch1")
    assert sketch["feature"] == _sketch_envelope()
    assert sketch["rolled_back"] is False
    # Row 2 — the extrude, referencing the sketch BY FEATURE ID.
    assert (extrude["order_index"], extrude["name"]) == (1, "Extrude1")
    assert extrude["feature"] == _extrude_envelope(sketch_id)
    assert extrude["rolled_back"] is False

    # Stored split (§1.3): type/param_version promoted to columns, params
    # holding only the payload — asserted against the DB, not the DTO.
    rows = asyncio.run(
        _fetch_all(
            any_db_url,
            sa.select(Feature.type, Feature.param_version, Feature.params).order_by(
                Feature.order_index
            ),
        )
    )
    assert [(row[0], row[1]) for row in rows] == [("sketch", 1), ("extrude", 1)]
    assert rows[0][2] == SKETCH_PARAMS
    assert rows[1][2] == _extrude_envelope(sketch_id)["params"]

    # §6 — the derived feature_dependencies row.
    edges = asyncio.run(
        _fetch_all(
            any_db_url,
            sa.select(
                FeatureDependency.part_id,
                FeatureDependency.feature_id,
                FeatureDependency.references_feature_id,
            ),
        )
    )
    assert [(str(e[0]), str(e[1]), str(e[2])) for e in edges] == [
        (part_id, extrude_id, sketch_id)
    ]


