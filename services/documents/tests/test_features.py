def test_reorder_applies_permutation_and_bar_survives(client: TestClient) -> None:
    part_id = _create_part(client)
    first = _create_feature(client, part_id, "SketchA", _sketch_envelope(), 0)
    second = _create_feature(client, part_id, "SketchB", _sketch_envelope(), 1)
    a_id: str = first["feature"]["id"]
    b_id: str = second["feature"]["id"]

    # Bar onto SketchA — SketchB is rolled back.
    response = client.put(
        f"/api/v1/parts/{part_id}/rollback",
        json={"expected_tree_version": 2, "rollback_feature_id": a_id},
        headers=_headers(),
    )
    assert response.status_code == 200

    response = client.put(
        f"/api/v1/parts/{part_id}/features/order",
        json={"expected_tree_version": 3, "order": [b_id, a_id]},
        headers=_headers(),
    )
    assert response.status_code == 200, response.text
    tree = response.json()
    assert [(f["id"], f["order_index"]) for f in tree["features"]] == [
        (b_id, 0),
        (a_id, 1),
    ]
    # The bar is a feature ID, not an index — it survives renumbering (§3)
    # and the rolled_back flags follow the NEW order.
    assert tree["rollback_feature_id"] == a_id
    assert [f["rolled_back"] for f in tree["features"]] == [False, False]


