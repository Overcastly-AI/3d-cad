def test_stale_version_rejected_on_every_mutation_route(client: TestClient) -> None:
    part_id = _create_part(client)
    sketch_id, extrude_id = _sketch_and_extrude(client, part_id)
    stale = 1  # current is 2

    requests = [
        client.patch(
            f"/api/v1/parts/{part_id}/features/{sketch_id}",
            json={"expected_tree_version": stale, "name": "Renamed"},
            headers=_headers(),
        ),
        client.delete(
            f"/api/v1/parts/{part_id}/features/{extrude_id}",
            params={"expected_tree_version": stale},
            headers=_headers(),
        ),
        client.put(
            f"/api/v1/parts/{part_id}/features/order",
            json={"expected_tree_version": stale, "order": [sketch_id, extrude_id]},
            headers=_headers(),
        ),
        client.put(
            f"/api/v1/parts/{part_id}/rollback",
            json={"expected_tree_version": stale, "rollback_feature_id": None},
            headers=_headers(),
        ),
    ]
    for response in requests:
        assert response.status_code == 422, response.text
        assert _envelope_error(response.json())["code"] == "stale_tree_version"


