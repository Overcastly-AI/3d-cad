def test_forward_reference_rejected_on_rolled_back_insert(client: TestClient) -> None:
    """Insert-after-the-bar must not see features BELOW the bar as targets:
    a reference to a feature after the insertion point is strictly forward."""
    part_id = _create_part(client)
    sketch_id, _extrude = _sketch_and_extrude(client, part_id)
    # Bar to the sketch (index 0): inserts now land at index 1.
    response = client.put(
        f"/api/v1/parts/{part_id}/rollback",
        json={"expected_tree_version": 2, "rollback_feature_id": sketch_id},
        headers=_headers(),
    )
    assert response.status_code == 200

    # A second sketch lands at index 1 and moves the bar; referencing IT from
    # a later insert is fine — but referencing the ORIGINAL extrude (now at
    # index 2) from a new insert at index 2 is forward → rejected.
    second = _create_feature(client, part_id, "Sketch2", _sketch_envelope(), 3)
    assert second["feature"]["order_index"] == 1

    tree = _tree(client, part_id)
    original_extrude = tree["features"][2]
    assert original_extrude["name"] == "Extrude1"
    response = client.post(
        f"/api/v1/parts/{part_id}/features",
        json={
            "name": "Extrude2",
            # Would extrude a "sketch"… except the target is the original
            # EXTRUDE at index 2 — forward of the insertion point (index 2).
            "feature": _extrude_envelope(original_extrude["id"]),
            "expected_tree_version": 4,
        },
        headers=_headers(),
    )
    assert response.status_code == 422
    assert _envelope_error(response.json())["code"] == "reference_not_earlier"


