    s1: str = sketch1["feature"]["id"]
    s2: str = sketch2["feature"]["id"]
    extrude = _create_feature(client, part_id, "Extrude1", _extrude_envelope(s1), 2)
    e_id: str = extrude["feature"]["id"]

    # Re-point the extrude from Sketch1 to Sketch2.
    response = client.patch(
        f"/api/v1/parts/{part_id}/features/{e_id}",
        json={"expected_tree_version": 3, "feature": _extrude_envelope(s2)},
        headers=_headers(),
    )
    assert response.status_code == 200, response.text

    # Sketch1 is now deletable (no dependents); Sketch2 is not.
    response = client.delete(
        f"/api/v1/parts/{part_id}/features/{s2}",
        params={"expected_tree_version": 4},
        headers=_headers(),
    )
    assert response.status_code == 409
    response = client.delete(
        f"/api/v1/parts/{part_id}/features/{s1}",
        params={"expected_tree_version": 4},
        headers=_headers(),
    )
    assert response.status_code == 200, response.text


