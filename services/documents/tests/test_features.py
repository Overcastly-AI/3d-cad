def test_lone_delete_of_referenced_feature_fails_at_commit(
    client: TestClient, any_db_url: str
) -> None:
    """The DB backstop behind the friendly 409: a delete that slips past the
    pre-check (simulated here with a direct row delete) still fails when the
    DEFERRED target-side FK is checked at COMMIT — a code-path bug can never
    silently corrupt the tree (design §2.3)."""
    part_id = _create_part(client)
    sketch_id, _extrude_id = _sketch_and_extrude(client, part_id)

    async def rogue_delete() -> None:
        engine = direct_engine(any_db_url)
        try:
            async with engine.begin() as connection:
                await connection.execute(
                    sa.delete(Feature).where(Feature.id == uuid.UUID(sketch_id))
                )
                # begin() commits on exit → the deferred FK fires HERE.
        finally:
            await engine.dispose()

    with pytest.raises(DBAPIError):
        asyncio.run(rogue_delete())

    # The tree survived intact.
    tree = _tree(client, part_id)
    assert [f["name"] for f in tree["features"]] == ["Sketch1", "Extrude1"]


