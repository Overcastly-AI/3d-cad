"""Architectural feet-inch lengths (HOUSE-DRAWINGS).

The sheet (``loft_wire.feet_inches``) and the screen (``formatFeetInches``,
packages/design) must never print different numbers. Both read
``packages/design/src/feetInches.vectors.json``: 10,000 lengths in mm, 5,000 of
them exact half-sixteenths (the rounding edge), 5,000 spread over +-20,000 mm,
each with its text. Every half-sixteenth's text is checked here against the
exact length it stands for (``n / 32`` in, rounded half up in Fractions),
independent of the implementation.

Regenerate with ``uv run python packages/loft-wire/tests/test_feet_inches.py``.
"""

import json
from fractions import Fraction
from pathlib import Path

import pytest
from loft_wire.feet_inches import feet_inches

IN = 25.4
VECTORS = (
    Path(__file__).resolve().parents[2] / "design" / "src" / "feetInches.vectors.json"
)

CASES = [
    (288, "24'-0\""),
    (192, "16'-0\""),
    (97.125, "8'-1 1/8\""),
    (82.5, "6'-10 1/2\""),
    (60, "5'-0\""),
    (84, "7'-0\""),
    (5.5, '5 1/2"'),
    (0.75, '3/4"'),
    (0, '0"'),
    (12.03125, "1'-0 1/16\""),
    (11.99, "1'-0\""),
    (-30, "-2'-6\""),
    # Half-sixteenths round up (the coordinator's case).
    (11 + 31 / 32, "1'-0\""),
    (1 / 32, '1/16"'),
    (60 + 3 / 32, "5'-0 1/8\""),
]


@pytest.mark.parametrize(("inches", "text"), CASES)
def test_feet_inches(inches: float, text: str) -> None:
    assert feet_inches(inches * IN) == text


def _exact_text(n32: int, negative: bool) -> str:
    """The text of exactly n32/32 in, half up, built from Fractions alone."""
    steps = int(Fraction(n32, 2) + Fraction(1, 2))
    feet, rest = divmod(steps, 192)
    inches, part = divmod(rest, 16)
    frac = "" if part == 0 else str(Fraction(part, 16))
    if feet:
        body = f"{feet}'-{inches}{' ' + frac if frac else ''}\""
    elif inches:
        body = f'{inches}{" " + frac if frac else ""}"'
    else:
        body = f'{frac}"' if frac else '0"'
    return f"-{body}" if negative and steps else body


def _vectors() -> list[tuple[float, str, int | None]]:
    """(mm, text, n32 or None) — regenerated by ``__main__`` below."""
    rows: list[tuple[float, str, int | None]] = []
    for i in range(5000):
        n32 = 2 * i + 1  # every odd 32nd up to 312 in
        mm = n32 / 32 * IN
        mm = -mm if i % 7 == 3 else mm
        rows.append((mm, feet_inches(mm), n32))
    seed = 20261029
    for _ in range(5000):
        seed = (seed * 6364136223846793005 + 1442695040888963407) % 2**64
        mm = (seed / 2**64) * 40000 - 20000
        rows.append((mm, feet_inches(mm), None))
    return rows


def test_the_shared_vectors_are_the_sheet() -> None:
    data = json.loads(VECTORS.read_text())
    assert len(data) == 10_000
    wrong = [(mm, text) for mm, text, _ in data if feet_inches(mm) != text]
    assert wrong == []


def test_every_half_sixteenth_rounds_up() -> None:
    data = json.loads(VECTORS.read_text())
    halves = [(mm, text, n32) for mm, text, n32 in data if n32 is not None]
    assert len(halves) == 5000
    assert [t for mm, t, n in halves if t != _exact_text(n, mm < 0)] == []


if __name__ == "__main__":
    VECTORS.write_text(
        "[\n"
        + ",\n".join(
            f"  [{mm!r}, {json.dumps(t)}, {json.dumps(n)}]" for mm, t, n in _vectors()
        )
        + "\n]\n"
    )
